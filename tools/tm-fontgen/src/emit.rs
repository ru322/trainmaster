//! 生成物(帯の PNG と `glyphs.rs`)の書き出し。時刻やパスは書かない(15 §4.6、§4.7)。

use crate::config::Strip;
use crate::error::FontgenError;
use crate::raster::Face;
use std::fmt::Write;

/// 8 ビット RGBA の画像。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Image {
    /// 幅。
    pub w: u32,
    /// 高さ。
    pub h: u32,
    /// 行優先の画素。
    pub px: Vec<[u8; 4]>,
}

impl Image {
    /// `fill` で塗った画像。
    pub fn new(w: u32, h: u32, fill: [u8; 4]) -> Image {
        Image {
            w,
            h,
            px: vec![fill; (w * h) as usize],
        }
    }

    /// 画素を返す(範囲外は透明)。
    pub fn get(&self, x: u32, y: u32) -> [u8; 4] {
        if x < self.w && y < self.h {
            self.px[(y * self.w + x) as usize]
        } else {
            [0; 4]
        }
    }

    /// 画素を書く(範囲外は無視)。
    pub fn set(&mut self, x: u32, y: u32, p: [u8; 4]) {
        if x < self.w && y < self.h {
            self.px[(y * self.w + x) as usize] = p;
        }
    }
}

/// 8 ビット RGBA の PNG を、圧縮とフィルタを固定して符号化する(15 AS-D-22)。
pub fn encode_png(img: &Image) -> Result<Vec<u8>, FontgenError> {
    let mut out = Vec::new();
    let mut enc = png::Encoder::new(&mut out, img.w, img.h);
    enc.set_color(png::ColorType::Rgba);
    enc.set_depth(png::BitDepth::Eight);
    enc.set_deflate_compression(png::DeflateCompression::Level(6));
    enc.set_filter(png::Filter::Adaptive);
    let io = |e: png::EncodingError| FontgenError::Read {
        path: "png".into(),
        message: e.to_string(),
    };
    let mut writer = enc.write_header().map_err(io)?;
    let bytes: Vec<u8> = img.px.iter().flatten().copied().collect();
    writer.write_image_data(&bytes).map_err(io)?;
    writer.finish().map_err(io)?;
    Ok(out)
}

/// Rust の文字リテラル。`'` と `\` と制御文字だけをエスケープする。
pub fn rust_char(c: char) -> String {
    match c {
        '\'' => "'\\''".into(),
        '\\' => "'\\\\'".into(),
        c if c.is_control() => format!("'\\u{{{:x}}}'", c as u32),
        c => format!("'{c}'"),
    }
}

/// `glyphs.rs` の中身。`positions` はグリフの通し番号の順の左上(ページの絶対座標)。
pub fn glyphs_rs(faces: &[Face], positions: &[(u32, u32)], strip: &Strip, sha256: &str) -> String {
    let mut s = String::from(
        "// @generated by tm-fontgen from assets/fonts/fontgen.toml — 手で編集しない\n",
    );
    let _ = writeln!(s, "pub const FONT_SHA256: &str = \"{sha256}\";");
    let _ = writeln!(
        s,
        "pub const FONT_STRIP: StripInfo = StripInfo {{ page: {}, y: {}, height: {} }};",
        strip.page, strip.y, strip.height
    );
    let _ = writeln!(s, "pub const GLYPH_COUNT: usize = {};", positions.len());
    s.push_str("pub static GLYPH_RECTS: [SpriteRect; GLYPH_COUNT] = [\n");
    let bitmaps = faces
        .iter()
        .flat_map(|f| &f.glyphs)
        .filter_map(|g| g.bitmap.as_ref());
    for (b, (x, y)) in bitmaps.zip(positions) {
        let _ = writeln!(
            s,
            "    SpriteRect {{ atlas: {}, x: {x}, y: {y}, w: {}, h: {} }},",
            strip.page, b.w, b.h
        );
    }
    s.push_str("];\n");
    let mut serial = 0u32;
    for f in faces {
        let upper = f.def.id.to_ascii_uppercase();
        let _ = writeln!(
            s,
            "static {upper}_GLYPHS: [GlyphEntry; {}] = [",
            f.glyphs.len()
        );
        for g in &f.glyphs {
            let ch = rust_char(g.ch);
            match &g.bitmap {
                Some(b) => {
                    let _ = writeln!(
                        s,
                        "    GlyphEntry {{ ch: {ch}, advance: {}, index: {serial}, w: {}, h: {}, x_off: {}, y_off: {} }},",
                        g.advance, b.w, b.h, b.x_off, b.y_off
                    );
                    serial += 1;
                }
                None => {
                    let _ = writeln!(
                        s,
                        "    GlyphEntry {{ ch: {ch}, advance: {}, index: NO_BITMAP, w: 0, h: 0, x_off: 0, y_off: 0 }},",
                        g.advance
                    );
                }
            }
        }
        s.push_str("];\n");
        let _ = writeln!(s, "static {upper}_ASCII: [u16; 95] = [");
        for c in ' '..='~' {
            match f.glyphs.binary_search_by_key(&c, |g| g.ch) {
                Ok(i) => {
                    let _ = writeln!(s, "    {i},");
                }
                Err(_) => s.push_str("    u16::MAX,\n"),
            }
        }
        s.push_str("];\n");
        let _ = writeln!(
            s,
            "pub static FACE_{upper}: FontFace = FontFace {{ id: FontId::{}, size_px: {}, ascent: {}, descent: {}, line_height: {}, full_advance: {}, glyphs: &{upper}_GLYPHS, ascii: &{upper}_ASCII }};",
            f.def.id, f.def.size_px, f.ascent, f.descent, f.def.line_height, f.def.size_px
        );
    }
    s
}
