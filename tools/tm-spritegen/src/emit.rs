//! 生成物(`sprites.rs`、`palette.rs`、PNG)の書き出し。時刻やパスは書かない。

use crate::atlas::Strip;
use crate::error::SpriteError;
use crate::image::Image;
use crate::palette::Palette;
use crate::resolve::Resolved;
use std::collections::BTreeMap;
use std::fmt::Write;

const DIRS: [&str; 8] = ["e", "ne", "n", "nw", "w", "sw", "s", "se"];
const VARIANTS: [&str; 5] = ["l1", "l0p", "l2p", "l0c", "l2c"];
const BAND_VARIANT: &str = "#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum BandVariant { Center, Lane0, Lane2, Lane0Conv, Lane2Conv }
";

/// 名前を定数名(大文字)にする。
pub fn const_name(name: &str) -> String {
    name.to_ascii_uppercase()
}

/// 8 ビット RGBA の PNG を、圧縮とフィルタを固定して符号化する(15 AS-D-22)。
pub fn encode_png(img: &Image) -> Result<Vec<u8>, SpriteError> {
    let mut out = Vec::new();
    let mut enc = png::Encoder::new(&mut out, img.w, img.h);
    enc.set_color(png::ColorType::Rgba);
    enc.set_depth(png::BitDepth::Eight);
    enc.set_deflate_compression(png::DeflateCompression::Level(6));
    enc.set_filter(png::Filter::Adaptive);
    let io = |e: png::EncodingError| SpriteError::Io {
        path: "png".into(),
        message: e.to_string(),
    };
    let mut writer = enc.write_header().map_err(io)?;
    let bytes: Vec<u8> = img.px.iter().flatten().copied().collect();
    writer.write_image_data(&bytes).map_err(io)?;
    writer.finish().map_err(io)?;
    Ok(out)
}

/// `palette.rs`(ドット絵の色の名前付き定数)。
pub fn palette_rs(pal: &Palette) -> String {
    let mut s = String::from("// @generated by tm-spritegen from assets/sprites/palette.ron\n");
    for c in &pal.colors {
        let [r, g, b, a] = c.rgba;
        let _ = writeln!(
            s,
            "pub const PAL_{}: Color = Color {{ r: {r}, g: {g}, b: {b}, a: {a} }};",
            const_name(&c.name)
        );
    }
    s
}

/// `sprites.rs` の 1 件分(名前の辞書順に並べた 1 行が 1 つの `SpriteId`)。
pub struct SpriteRow<'a> {
    /// 名前。
    pub name: &'a str,
    /// 左上(ページの絶対座標)。
    pub pos: (u32, u32),
    /// アトラスの画素の寸法。
    pub texels: (u32, u32),
    /// 大きい版の左上と寸法。
    pub alt: Option<((u32, u32), (u32, u32))>,
    /// 設計の寸法(`SpriteMeta`)。
    pub size: (u32, u32),
    /// 基準点。
    pub pivot: (i32, i32),
    /// tint 前提か。
    pub tint: bool,
}

/// `sprites.rs` を書く。表を成す名前が一部だけあれば SG-E02。
pub fn sprites_rs(
    rows: &[SpriteRow<'_>],
    resolved: &Resolved,
    strip: &Strip,
) -> Result<String, SpriteError> {
    let ids: BTreeMap<&str, usize> = rows.iter().enumerate().map(|(i, r)| (r.name, i)).collect();
    let mut s =
        String::from("// @generated by tm-spritegen from assets/sprites — 手で編集しない\n");
    let _ = writeln!(
        s,
        "pub const SPRITE_STRIP: StripInfo = StripInfo {{ page: {}, y: {}, height: {} }};",
        strip.page, strip.y, strip.height
    );
    let _ = writeln!(
        s,
        "pub const SPRITE_RENDER_SCALE: u32 = {};",
        strip.render_scale
    );
    let _ = writeln!(s, "pub const SPRITE_COUNT: usize = {};", rows.len());
    let _ = writeln!(s, "pub static SPRITE_RECTS: [SpriteRect; SPRITE_COUNT] = [");
    for r in rows {
        let _ = writeln!(
            s,
            "    SpriteRect {{ atlas: {}, x: {}, y: {}, w: {}, h: {} }},",
            strip.page, r.pos.0, r.pos.1, r.texels.0, r.texels.1
        );
    }
    s.push_str("];\n");
    let alts: Vec<(usize, &SpriteRow<'_>)> = rows
        .iter()
        .enumerate()
        .filter(|(_, r)| r.alt.is_some())
        .collect();
    let _ = writeln!(s, "pub const SPRITE_ALT_COUNT: usize = {};", alts.len());
    s.push_str("pub static SPRITE_ALT: [SpriteAlt; SPRITE_ALT_COUNT] = [\n");
    for (i, r) in alts {
        let ((x, y), (w, h)) = r.alt.expect("大きい版");
        let _ = writeln!(
            s,
            "    SpriteAlt {{ id: SpriteId({i}), rect: SpriteRect {{ atlas: {}, x: {x}, y: {y}, w: {w}, h: {h} }} }},",
            strip.page
        );
    }
    s.push_str("];\n");
    let _ = writeln!(s, "pub static SPRITE_META: [SpriteMeta; SPRITE_COUNT] = [");
    for r in rows {
        let _ = writeln!(
            s,
            "    SpriteMeta {{ w: {}, h: {}, pivot_x: {}, pivot_y: {}, tintable: {} }},",
            r.size.0, r.size.1, r.pivot.0, r.pivot.1, r.tint
        );
    }
    s.push_str("];\n");
    let _ = writeln!(s, "pub static SPRITE_NAMES: [&str; SPRITE_COUNT] = [");
    for r in rows {
        let _ = writeln!(s, "    \"{}\",", r.name);
    }
    s.push_str("];\n");
    for (i, r) in rows.iter().enumerate() {
        let _ = writeln!(
            s,
            "pub const {}: SpriteId = SpriteId({i});",
            const_name(r.name)
        );
    }
    let dir_names = |prefix: &str, suffix: &str| -> Vec<String> {
        DIRS.iter()
            .map(|d| format!("{prefix}{d}{suffix}"))
            .collect()
    };
    let bands = |prefix: &str| -> Vec<Vec<String>> {
        DIRS.iter()
            .map(|d| {
                VARIANTS
                    .iter()
                    .map(|v| format!("{prefix}{d}_{v}"))
                    .collect()
            })
            .collect()
    };
    if let Some(tile) = resolved.track_tile {
        let [a, b, c, d] = crate::draw::TRACK_PENS;
        let [e, f] = crate::draw::TRACK_LANES;
        let _ = writeln!(s, "pub const TRACK_TILE: u16 = {tile};");
        let _ = writeln!(s, "pub const TRACK_PENS: [u16; 4] = [{a}, {b}, {c}, {d}];");
        let _ = writeln!(s, "pub const TRACK_LANES: [u16; 2] = [{e}, {f}];");
    }
    emit_table(&mut s, &ids, "TRN", &dir_names("trn_", ""))?;
    emit_table(&mut s, &ids, "TRN_GLASS", &dir_names("trn_glass_", ""))?;
    emit_table(&mut s, &ids, "TRK_RAIL_O", &dir_names("trk_rail_o_", ""))?;
    emit_table(&mut s, &ids, "TRK_RAIL_F", &dir_names("trk_rail_f_", ""))?;
    if emit_nested(&mut s, &ids, "TRK_BAND_O", &bands("trk_band_o_"))? {
        s.push_str(BAND_VARIANT);
    }
    emit_nested(&mut s, &ids, "TRK_BAND_F", &bands("trk_band_f_"))?;
    let dots: Vec<String> = (0..=10).map(|n| format!("pax_dots_{n}")).collect();
    emit_table(&mut s, &ids, "PAX_DOTS", &dots)?;
    let line_no: Vec<String> = (1..=6).map(|n| format!("ico_line_no_{n}")).collect();
    emit_table(&mut s, &ids, "LINE_NO", &line_no)?;
    for a in &resolved.anims {
        let first = const_name(&format!("{}_f0", a.name));
        let _ = writeln!(
            s,
            "pub const ANIM_{}: Anim = Anim {{ first: {first}, frames: {}, frame_ms: {}, looping: {} }};",
            const_name(&a.name),
            a.frames,
            a.anim.frame_ms,
            a.anim.looping
        );
    }
    for n in &resolved.nines {
        let parts: Vec<String> = crate::draw::NINE_SUFFIXES
            .iter()
            .map(|sfx| const_name(&format!("{}_{sfx}", n.name)))
            .collect();
        let _ = writeln!(
            s,
            "pub const NS_{}: NineSlice = NineSlice {{ parts: [{}], corner: {} }};",
            const_name(&n.name),
            parts.join(", "),
            n.corner
        );
    }
    Ok(s)
}

fn present(ids: &BTreeMap<&str, usize>, names: &[String]) -> Result<bool, SpriteError> {
    let count = names
        .iter()
        .filter(|n| ids.contains_key(n.as_str()))
        .count();
    if count != 0 && count != names.len() {
        let missing = names
            .iter()
            .find(|n| !ids.contains_key(n.as_str()))
            .cloned();
        return Err(SpriteError::Name {
            name: missing.unwrap_or_default(),
            reason: "表を成す名前の一部が欠けている".into(),
        });
    }
    Ok(count != 0)
}

fn emit_table(
    s: &mut String,
    ids: &BTreeMap<&str, usize>,
    table: &str,
    names: &[String],
) -> Result<(), SpriteError> {
    if present(ids, names)? {
        let items: Vec<String> = names.iter().map(|n| const_name(n)).collect();
        let _ = writeln!(
            s,
            "pub const {table}: [SpriteId; {}] = [{}];",
            names.len(),
            items.join(", ")
        );
    }
    Ok(())
}

fn emit_nested(
    s: &mut String,
    ids: &BTreeMap<&str, usize>,
    table: &str,
    rows: &[Vec<String>],
) -> Result<bool, SpriteError> {
    let flat: Vec<String> = rows.iter().flatten().cloned().collect();
    let found = present(ids, &flat)?;
    if found {
        let items: Vec<String> = rows
            .iter()
            .map(|r| {
                let inner: Vec<String> = r.iter().map(|n| const_name(n)).collect();
                format!("[{}]", inner.join(", "))
            })
            .collect();
        let _ = writeln!(
            s,
            "pub const {table}: [[SpriteId; {}]; {}] = [{}];",
            rows[0].len(),
            rows.len(),
            items.join(", ")
        );
    }
    Ok(found)
}
