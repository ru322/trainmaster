//! `sounds.rs` と `audio_manifest.txt` の生成(14 §5.6、15 §3.6)。

use std::fmt::Write as _;

use crate::validate::BUDGET_BYTES;
use crate::wav::fnv64;
use crate::{Sound, SoundKind};

fn kind_name(k: SoundKind) -> &'static str {
    match k {
        SoundKind::Se => "Se",
        SoundKind::Bgm => "Bgm",
        SoundKind::Jingle => "Jingle",
    }
}

/// 3 桁ごとに `_` で区切る(例 `22_050`)。
fn grouped(n: u64) -> String {
    let s = n.to_string();
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if i > 0 && (s.len() - i).is_multiple_of(3) {
            out.push('_');
        }
        out.push(c);
    }
    out
}

/// `sounds.rs` の中身。`sounds` は名前の辞書順で、その順に `SoundId` を振る。
pub fn sounds_rs(sounds: &[Sound]) -> String {
    let mut s = String::new();
    s.push_str(
        "// @generated by tm-audiogen (format 1). DO NOT EDIT. 元: assets/audio/*.ron\n\
         // SoundId は名前の辞書順(バイト順)に 0 から振る [02 D33]\n",
    );
    for (i, snd) in sounds.iter().enumerate() {
        let _ = writeln!(
            s,
            "pub const {}: SoundId = SoundId({i});",
            snd.name.to_ascii_uppercase()
        );
    }
    let _ = writeln!(s, "pub const SOUND_COUNT: usize = {};", sounds.len());
    s.push_str(
        "\n// SoundId の番号順。wav は 44 バイトのヘッダを含むファイル全体\n\
         pub static SOUND_ENTRIES: [SoundEntry; SOUND_COUNT] = [\n",
    );
    for snd in sounds {
        let loop_start = match snd.loop_start {
            Some(v) => format!("Some({})", grouped(u64::from(v))),
            None => "None".to_string(),
        };
        let _ = writeln!(
            s,
            "    SoundEntry {{ name: \"{name}\", kind: SoundKind::{kind}, loop_start: {loop_start},\n                 \
             wav: &AlignedWav(*include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/generated/audio/{name}.wav\"))) }},",
            name = snd.name,
            kind = kind_name(snd.kind),
        );
    }
    s.push_str("];\n");
    s
}

/// `audio_manifest.txt` の中身(人が読む一覧。時刻や環境の情報は書かない)。
pub fn manifest(sounds: &[Sound]) -> String {
    let mut s = String::from(
        "# @generated by tm-audiogen (format 1)\n\
         # id name                 kind    samples  ms     bytes    loop_start peak  clipped fnv64\n",
    );
    let mut total = 0u64;
    for (i, snd) in sounds.iter().enumerate() {
        let wav = snd.wav();
        total += wav.len() as u64;
        let loop_start = snd
            .loop_start
            .map_or_else(|| "-".to_string(), |v| v.to_string());
        let _ = writeln!(
            s,
            "{:<3} {:<20} {:<7} {:<8} {:<6} {:<8} {:<10} {:<5} {:<7} 0x{:016x}",
            i,
            snd.name,
            kind_name(snd.kind),
            snd.samples.len(),
            snd.duration_ms(),
            wav.len(),
            loop_start,
            snd.peak,
            snd.clipped,
            fnv64(&wav),
        );
    }
    let permille = total * 1000 / BUDGET_BYTES;
    let _ = writeln!(
        s,
        "total_bytes {total} / budget {BUDGET_BYTES} ({}.{}%)",
        permille / 10,
        permille % 10
    );
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    fn snd(name: &str, kind: SoundKind, loop_start: Option<u32>) -> Sound {
        Sound {
            name: name.to_string(),
            kind,
            samples: vec![0, 1, -1],
            loop_start,
            clipped: 0,
            peak: 1,
        }
    }

    #[test]
    fn a11_sounds_rs_shape() {
        let sounds = [
            snd("bgm_game_1", SoundKind::Bgm, Some(22_050)),
            snd("jingle_goal", SoundKind::Jingle, None),
            snd("se_coin", SoundKind::Se, None),
        ];
        let rs = sounds_rs(&sounds);
        let want = r#"// @generated by tm-audiogen (format 1). DO NOT EDIT. 元: assets/audio/*.ron
// SoundId は名前の辞書順(バイト順)に 0 から振る [02 D33]
pub const BGM_GAME_1: SoundId = SoundId(0);
pub const JINGLE_GOAL: SoundId = SoundId(1);
pub const SE_COIN: SoundId = SoundId(2);
pub const SOUND_COUNT: usize = 3;

// SoundId の番号順。wav は 44 バイトのヘッダを含むファイル全体
pub static SOUND_ENTRIES: [SoundEntry; SOUND_COUNT] = [
    SoundEntry { name: "bgm_game_1", kind: SoundKind::Bgm, loop_start: Some(22_050),
                 wav: &AlignedWav(*include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/generated/audio/bgm_game_1.wav"))) },
    SoundEntry { name: "jingle_goal", kind: SoundKind::Jingle, loop_start: None,
                 wav: &AlignedWav(*include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/generated/audio/jingle_goal.wav"))) },
    SoundEntry { name: "se_coin", kind: SoundKind::Se, loop_start: None,
                 wav: &AlignedWav(*include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/generated/audio/se_coin.wav"))) },
];
"#;
        assert_eq!(rs, want);
        assert!(rs.contains(
            "    SoundEntry { name: \"se_coin\", kind: SoundKind::Se, loop_start: None,\n                 wav: &AlignedWav(*include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/generated/audio/se_coin.wav\"))) },"
        ));
    }

    #[test]
    fn grouping() {
        assert_eq!(grouped(0), "0");
        assert_eq!(grouped(999), "999");
        assert_eq!(grouped(22_050), "22_050");
        assert_eq!(grouped(1_534_050), "1_534_050");
    }

    #[test]
    fn manifest_columns() {
        let m = manifest(&[snd("bgm_game_1", SoundKind::Bgm, Some(1))]);
        let lines: Vec<&str> = m.lines().collect();
        assert_eq!(lines.len(), 4);
        assert!(lines[2].starts_with(
            "0   bgm_game_1           Bgm     3        0      50       1          1     0       0x"
        ));
        assert_eq!(lines[3], "total_bytes 50 / budget 25165824 (0.0%)");
        assert!(!m.contains('\r'));
    }
}
